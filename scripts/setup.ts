/**
 * `pnpm run setup` — writes portal.config.ts for one LGU or DPWH district
 * engineering office, using the live API and local PSGC geographic data to
 * find exact names, constituent LGUs, and legislative districts.
 *
 *   pnpm run setup                     interactive
 *   pnpm run setup -- --list-offices   every DPWH office, named as published (scope.offices)
 *   pnpm run setup -- --list-districts every legislative district id
 *   pnpm run setup -- --out=my.config.ts  write somewhere else
 *
 * The file it writes is plain TypeScript; edit it by hand afterwards.
 */
import { existsSync, writeFileSync } from 'node:fs';
import { dirname, relative, resolve } from 'node:path';
import { createInterface } from 'node:readline/promises';
import { stdin, stdout, argv, cwd, env, exit } from 'node:process';
import { createClient } from '../src/api/client.ts';
import type { DistrictCard } from '../src/api/types.ts';
import { DEFAULT_API, type PlaceQuery, type PortalConfig, type PortalKind } from '../src/config.ts';
import psgc from '../src/data/psgc.json';

interface PsgcProvince {
  name: string;
  code: string;
  region_key: string;
  cities: string[];
  municipalities: string[];
  lgus: string[];
}

interface PsgcData {
  provinces: Record<string, PsgcProvince>;
  namesakeTowns: Record<string, string[]>;
}

const psgcTyped = psgc as PsgcData;
const api = createClient(env.VITE_API_BASE || DEFAULT_API);
// --out=path writes somewhere else (to try it without touching your config).
const OUT = resolve(argv.find((a) => a.startsWith('--out='))?.slice('--out='.length) ?? resolve(import.meta.dirname, '..', 'portal.config.ts'));

async function allDistricts(): Promise<DistrictCard[]> {
  const res = await api.districts({ limit: 254, sort: 'name' });
  return res.data.districts;
}

/** The office name exactly as the documents publish it (what the API's `office` filter matches). */
async function printedOfficeName(officeId: string, districtId: string): Promise<string> {
  const d = await api.district(districtId);
  const office = d.data.offices.find((o) => o.id === officeId);
  const years = office?.years ?? [];
  const label =
    years.find((y) => y.fy === 2027 && y.stage === 'hgab3' && y.matched_label)?.matched_label ??
    years.find((y) => y.fy === 2027 && y.stage === 'nep' && y.matched_label)?.matched_label;
  return label ?? (office?.name ?? officeId).replace(/\bDEO$/, 'District Engineering Office');
}

interface OfficeChoice { id: string; name: string; tier: string; districts: DistrictCard[] }

function officesOf(districts: DistrictCard[]): OfficeChoice[] {
  const byId = new Map<string, OfficeChoice>();
  for (const d of districts) {
    for (const o of d.offices) {
      const seen = byId.get(o.id) ?? { id: o.id, name: o.name, tier: o.tier, districts: [] };
      seen.districts.push(d);
      byId.set(o.id, seen);
    }
  }
  return [...byId.values()].sort((a, b) => a.name.localeCompare(b.name));
}

async function countPlace(p: PlaceQuery): Promise<Record<string, number>> {
  const out: Record<string, number> = {};
  for (const ds of ['dpwh', 'fmr', 'hfep', 'nia'] as const) {
    const r = await api.get<{ total: number }>(`/datasets/${ds}/projects`, { q: p.q ?? p.label, region: p.region, limit: 1 });
    out[ds] = r.data.total;
  }
  return out;
}

const slug = (s: string) => s.toLowerCase().normalize('NFD').replace(/[̀-ͯ]/g, '').replace(/ñ/g, 'n').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

/** The import path from the written file to src/config.ts. */
const CONFIG_IMPORT = (() => {
  const rel = relative(dirname(OUT), resolve(import.meta.dirname, '..', 'src', 'config')).replace(/\\/g, '/');
  return rel.startsWith('.') ? rel : `./${rel}`;
})();

function render(config: PortalConfig): string {
  const json = JSON.stringify(config, null, 2)
    // Unquote keys for readability; values stay JSON.
    .replace(/^(\s*)"([a-zA-Z_][a-zA-Z0-9_]*)":/gm, '$1$2:');
  return `/**
 * This portal's configuration. Generated by \`pnpm run setup\` on ${new Date().toISOString().slice(0, 10)}; edit freely.
 * What each field means: src/config.ts. Check it against the live API: \`pnpm run check\`.
 */
import { defineConfig } from '${CONFIG_IMPORT}';

export default defineConfig(${json});
`;
}

async function main() {
  if (argv.includes('--list-offices')) {
    // The name as published is what scope.offices needs; it comes from each
    // office's district page, so fetch those a few at a time.
    const offices = officesOf(await allDistricts());
    const printed: string[] = [];
    for (let i = 0; i < offices.length; i += 6) {
      const batch = offices.slice(i, i + 6);
      printed.push(...(await Promise.all(batch.map((o) => printedOfficeName(o.id, o.districts[0].id)))));
    }
    offices.forEach((o, i) => {
      console.log(`${printed[i].padEnd(52)} Tier ${o.tier}  ${o.districts.map((d) => d.id).join(', ')}`);
    });
    return;
  }
  if (argv.includes('--list-districts')) {
    for (const d of await allDistricts()) {
      console.log(`${d.id.padEnd(40)} ${d.label.padEnd(44)} ${d.region ?? ''}`);
    }
    return;
  }

  // Lines are read through an iterator, which buffers them, so answers can
  // also be piped in (printf '2\nBohol\n…' | pnpm run setup).
  const rl = createInterface({ input: stdin, terminal: false });
  const lines = rl[Symbol.asyncIterator]();
  const ask = async (q: string, fallback = '') => {
    stdout.write(fallback ? `${q} [${fallback}] ` : `${q} `);
    const next = await lines.next();
    if (next.done) throw new Error('\nInput ended before setup finished.');
    if (!stdin.isTTY) stdout.write(next.value + '\n');
    return next.value.trim() || fallback;
  };
  const pick = async <T>(items: T[], show: (t: T) => string, what: string): Promise<T> => {
    if (items.length === 1) return items[0];
    items.slice(0, 30).forEach((t, i) => console.log(`  ${String(i + 1).padStart(2)}. ${show(t)}`));
    if (items.length > 30) console.log(`  … ${items.length - 30} more; narrow the search.`);
    for (;;) {
      const n = Number(await ask(`Which ${what}? (number)`));
      if (Number.isInteger(n) && n >= 1 && n <= Math.min(items.length, 30)) return items[n - 1];
    }
  };

  console.log('\nBuild a FY2027 budget transparency portal for one LGU or DPWH office.\n');
  if (existsSync(OUT)) console.log(`${relative(cwd(), OUT) || OUT} exists and will be overwritten at the end (stop with Ctrl+C).\n`);

  const kindAnswer = await ask('Portal for a (1) DPWH district engineering office, (2) province, (3) city, (4) municipality?', '2');
  const kind: PortalKind = (['deo', 'province', 'city', 'municipality'] as const)[Math.max(0, Math.min(3, Number(kindAnswer) - 1))] ?? 'province';

  console.log('\nLoading districts and offices from the API…');
  const districts = await allDistricts();
  const offices = officesOf(districts);

  let name: string;
  let shortName: string;
  let scopeOffices: string[] = [];
  let places: PlaceQuery[] = [];
  let districtIds: string[] = [];
  let excludeTerms: string[] = [];

  if (kind === 'deo') {
    let matches: OfficeChoice[] = [];
    while (!matches.length) {
      const q = (await ask('Search for the office (e.g. "Bohol 1st"):')).toLowerCase();
      matches = offices.filter((o) => o.name.toLowerCase().includes(q));
      if (!matches.length) console.log('  No office matches. Try the province or city name.');
    }
    const office = await pick(matches, (o) => `${o.name} · Tier ${o.tier} · serves ${o.districts.map((d) => d.label).join('; ')}`, 'office');
    const printed = await printedOfficeName(office.id, office.districts[0].id);
    name = printed;
    shortName = office.name;
    scopeOffices = [printed];
    districtIds = office.districts.map((d) => d.id);
  } else if (kind === 'province') {
    let provinceName = '';
    for (;;) {
      provinceName = await ask('Province name (e.g. "Rizal", "Bohol", "Iloilo"):');
      if (provinceName) break;
    }

    // Match with PSGC data if available
    const psgcKey = Object.keys(psgcTyped.provinces).find((k) => k.toLowerCase() === provinceName.toLowerCase());
    const psgcProv = psgcKey ? psgcTyped.provinces[psgcKey] : null;

    if (psgcProv) {
      console.log(`\nFound ${psgcKey} in PSGC: Region ${psgcProv.region_key}, ${psgcProv.cities.length} city(ies), ${psgcProv.municipalities.length} municipality(ies).`);
    }

    // Find all legislative districts belonging to the province OR its component cities
    const targetJurisdictions = new Set<string>();
    targetJurisdictions.add(provinceName.toLowerCase());
    targetJurisdictions.add(`${provinceName.toLowerCase()} province`);
    if (psgcProv) {
      for (const c of psgcProv.cities) {
        targetJurisdictions.add(c.toLowerCase());
        targetJurisdictions.add(`${c.toLowerCase()} city`);
        targetJurisdictions.add(`city of ${c.toLowerCase()}`);
      }
    }

    const mine = districts.filter((d) => targetJurisdictions.has(d.jurisdiction.toLowerCase()));
    districtIds = mine.map((d) => d.id);
    const mineOffices = officesOf(mine);

    console.log(`${provinceName}: ${mine.length} legislative district(s), DPWH offices: ${mineOffices.map((o) => o.name).join(', ') || 'none listed'}.`);
    const shared = mineOffices.filter((o) => o.districts.length !== offices.find((x) => x.id === o.id)?.districts.length);
    scopeOffices = await Promise.all(mineOffices.map((o) => printedOfficeName(o.id, o.districts[0].id)));
    if (shared.length) console.log(`  Note: ${shared.map((o) => o.name).join(', ')} also serve(s) districts outside ${provinceName}; their lines are listed whole.`);

    const regionKey = psgcProv?.region_key ?? mine[0]?.region_key ?? undefined;

    // Provincial place query (the scoping engine filters non-local lines automatically using PSGC constituent LGUs)
    places = [
      {
        label: psgcKey || provinceName,
        q: psgcKey || provinceName,
        region: regionKey,
      },
    ];

    // Default excludeTerms for provinces named after national heroes / historical figures
    if (/^(rizal|quezon|quirino|magsaysay)$/i.test(provinceName)) {
      excludeTerms = ['Memorial', 'Sports Complex', 'Shrine', 'High School', 'Rizal Park', 'State University'];
      console.log(`  Applied standard excludeTerms for hero-named province: ${excludeTerms.join(', ')}`);
    }

    name = `Province of ${psgcKey || provinceName}`;
    shortName = psgcKey || provinceName;
  } else {
    // City or Municipality
    let place = '';
    for (;;) {
      place = await ask(kind === 'city' ? 'City name (e.g. "Antipolo", "Quezon City"):' : 'Municipality name (e.g. "Morong", "Cainta"):');
      if (place) break;
    }

    const namesakes = psgcTyped.namesakeTowns[place.toLowerCase()];
    if (namesakes && namesakes.length > 1) {
      console.log(`\nNotice: "${place}" exists in multiple provinces: ${namesakes.join(', ')}.`);
    }

    const province = await ask('Province it is in:');
    const psgcKey = Object.keys(psgcTyped.provinces).find((k) => k.toLowerCase() === province.toLowerCase());
    const psgcProv = psgcKey ? psgcTyped.provinces[psgcKey] : null;

    const provDistricts = districts.filter((d) => {
      const j = d.jurisdiction.toLowerCase();
      return j === province.toLowerCase() || j === place.toLowerCase() || j === `${place.toLowerCase()} city`;
    });
    const region = psgcProv?.region_key ?? provDistricts[0]?.region_key ?? undefined;

    const useQualified = namesakes && namesakes.length > 1;

    const candidates: PlaceQuery[] = [
      { label: place, q: place, region },
      { label: place, q: `${place} ${province}`, region },
    ];

    console.log('\nChecking how many project titles name it…');
    for (const c of candidates) {
      const counts = await countPlace(c);
      console.log(`  q="${c.q}"${region ? ` region=${region}` : ''}: ${Object.entries(counts).map(([k, v]) => `${k} ${v}`).join(', ')}`);
    }

    const which = await ask(`Use (1) "${place}" alone, or (2) "${place} ${province}" (recommended to avoid false matches)?`, useQualified ? '2' : '1');
    places = [candidates[which === '2' ? 1 : 0]];

    if (provDistricts.length) {
      const d = await pick(provDistricts, (x) => x.label, 'legislative district is it in');
      districtIds = [d.id];
    }

    name = kind === 'city' ? (/(^city of | city$)/i.test(place) ? place : `${place} City`) : `Municipality of ${place}`;
    shortName = place;
  }

  name = await ask('Portal name:', name);
  shortName = await ask('Short name for headings:', shortName);
  const operator = await ask('Who runs this portal (organisation name):', 'Your organisation');
  const id = await ask('Portal id (sent with citizen reports):', slug(shortName));
  rl.close();

  const config: PortalConfig = {
    id,
    kind,
    name,
    shortName,
    operator: { name: operator },
    scope: {
      offices: scopeOffices,
      places,
      districts: districtIds,
      exclude: [],
      ...(excludeTerms.length ? { excludeTerms } : {}),
    },
    reporting: { enabled: false },
  };
  writeFileSync(OUT, render(config));
  console.log(`\nWrote ${OUT}.\nNext: pnpm run check   (counts every query against the live API)\n      pnpm run dev`);
}

main().catch((err) => {
  console.error(err instanceof Error ? err.message : err);
  exit(1);
});
